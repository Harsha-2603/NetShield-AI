import streamlit as st
import pandas as pd
import numpy as np
import joblib

import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parents[2]

if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from src.database import (
    initialize_database,
    save_review,
    get_reviews
)

initialize_database()
# ==========================================
# Page configuration
# ==========================================

st.set_page_config(
    page_title="NetShield AI - Alert Investigation",
    page_icon="🚨",
    layout="wide"
)

# ==========================================
# Load data
# ==========================================

ALERTS_PATH = "data/processed/alerts.csv"

# IMPORTANT:
# In your dataset copy, this file contains the 82,332-row
# test set used by NetShield.
TEST_PATH = "data/raw/UNSW_NB15_training-set.csv"

alerts = pd.read_csv(ALERTS_PATH)
test_data = pd.read_csv(TEST_PATH)


LOGISTIC_MODEL_PATH = "models/logistic_binary.pkl"

logistic_model = joblib.load(LOGISTIC_MODEL_PATH)

log_preprocessor = logistic_model.named_steps["preprocessor"]
log_classifier = logistic_model.named_steps["classifier"]

# ==========================================
# Title
# ==========================================

st.title("🚨 Alert Investigation")

st.write(
    "Investigate individual network-flow alerts generated by NetShield AI."
)

# ==========================================
# Select alert
# ==========================================

alert_ids = alerts["flow_index"].tolist()

# ==========================================
# Select alert
# ==========================================

alert_ids = alerts["flow_index"].tolist()

default_index = 0

if "selected_flow_id" in st.session_state:
    selected_flow_id = st.session_state["selected_flow_id"]

    if selected_flow_id in alert_ids:
        default_index = alert_ids.index(selected_flow_id)

selected_id = st.selectbox(
    "Select Flow / Alert",
    alert_ids,
    index=default_index
)

# ==========================================
# Get selected records
# ==========================================

alert = alerts[
    alerts["flow_index"] == selected_id
].iloc[0]

flow = test_data.iloc[int(selected_id)]

# ==========================================
# Alert summary
# ==========================================

st.divider()

st.subheader(f"Alert — Flow {selected_id}")

col1, col2, col3, col4 = st.columns(4)

with col1:
    st.metric(
        "Prediction",
        alert["prediction"]
    )

with col2:
    st.metric(
        "Attack Probability",
        f"{alert['attack_probability'] * 100:.2f}%"
    )

with col3:
    st.metric(
        "Attack Type",
        alert["attack_type"]
    )

with col4:
    st.metric(
        "Severity",
        alert["severity"]
    )

# ==========================================
# Severity
# ==========================================

st.subheader("Threat Assessment")

col1, col2 = st.columns(2)

with col1:
    st.write(
        f"**Severity Score:** "
        f"{alert['severity_score']:.2f}"
    )

with col2:
    st.write(
        f"**Flow Bytes:** "
        f"{int(alert['flow_bytes']):,}"
    )

# ==========================================
# Network flow details
# ==========================================

st.divider()

st.subheader("Network Flow Details")

details = {
    "Duration": flow["dur"],
    "Protocol": flow["proto"],
    "Service": flow["service"],
    "State": flow["state"],
    "Source Packets": flow["spkts"],
    "Destination Packets": flow["dpkts"],
    "Source Bytes": flow["sbytes"],
    "Destination Bytes": flow["dbytes"],
    "Source Loss": flow["sloss"],
    "Destination Loss": flow["dloss"],
    "Source Load": flow["sload"],
    "Destination Load": flow["dload"],
    "Source Jitter": flow["sjit"],
    "Destination Jitter": flow["djit"],
}

details_df = pd.DataFrame(
    details.items(),
    columns=["Feature", "Value"]
)

st.dataframe(
    details_df,
    use_container_width=True,
    hide_index=True
)

# ==========================================
# Explanation
# ==========================================

st.divider()


# ==========================================
# Real model explanation
# ==========================================


# Transform selected flow
X_explain = test_data.iloc[[int(selected_id)]]

X_explain_transformed = log_preprocessor.transform(
    X_explain.drop(columns=["id", "label", "attack_cat"])
)

# Convert sparse matrix to dense if necessary
if hasattr(X_explain_transformed, "toarray"):
    x_values = X_explain_transformed.toarray().ravel()
else:
    x_values = np.asarray(
        X_explain_transformed
    ).ravel()

# Get processed feature names
feature_names = (
    log_preprocessor
    .get_feature_names_out()
)

# Get Logistic Regression coefficients
coefficients = log_classifier.coef_[0]

# Calculate contribution
contributions = x_values * coefficients

explanation_df = pd.DataFrame({
    "Feature": feature_names,
    "Value": x_values,
    "Coefficient": coefficients,
    "Contribution": contributions
})

# Features pushing toward Attack
positive = (
    explanation_df[
        explanation_df["Contribution"] > 0
    ]
    .sort_values(
        "Contribution",
        ascending=False
    )
    .head(10)
)

# Features pushing away from Attack
negative = (
    explanation_df[
        explanation_df["Contribution"] < 0
    ]
    .sort_values(
        "Contribution"
    )
    .head(10)
)

st.write("### Factors increasing attack likelihood")

st.dataframe(
    positive[
        ["Feature", "Value", "Contribution"]
    ],
    use_container_width=True,
    hide_index=True
)

st.write("### Factors decreasing attack likelihood")

st.dataframe(
    negative[
        ["Feature", "Value", "Contribution"]
    ],
    use_container_width=True,
    hide_index=True
)

# ==========================================
# Analyst status
# ==========================================

st.subheader("Analyst Review")

status = st.selectbox(
    "Alert Status",
    [
        "Needs Investigation",
        "Confirmed Attack",
        "False Positive",
        "Benign"
    ]
)

comment = st.text_area(
    "Analyst Comment"
)

if st.button("Save Review"):

    save_review(
        selected_id,
        status,
        comment
    )

    st.success(
        f"Review saved for Flow {selected_id}."
    )

st.divider()

st.subheader("Review History")

review_history = get_reviews(
    selected_id
)

if review_history.empty:

    st.info(
        "No analyst reviews recorded for this flow."
    )

else:

    st.dataframe(
        review_history,
        use_container_width=True,
        hide_index=True
    )